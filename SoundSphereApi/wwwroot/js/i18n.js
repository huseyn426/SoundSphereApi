const dicts = { ru, en };
// Get current language from html tag (set by server) or fallback to en
let currentLang = document.documentElement.lang || 'en';

window.t = function(key, params = {}) {
    let value = dicts[currentLang][key];
    if (value === undefined) {
        if (currentLang !== 'en') {
            value = dicts['en'][key];
        }
        if (value === undefined) return key;
    }

    if (typeof value === 'string' && Object.keys(params).length > 0) {
        let result = value;
        for (const [k, v] of Object.entries(params)) {
            result = result.replace(`{${k}}`, v);
        }
        return result;
    }
    
    return value;
};

window.setLanguage = function(lang) {
    if (dicts[lang]) {
        currentLang = lang;
        document.documentElement.lang = lang;
        
        // Update all data-i18n elements
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            el.textContent = window.t(key);
        });
        
        // Update placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.placeholder = window.t(key);
        });
        
        // Update active class on language togglers
        document.querySelectorAll('.lang-link').forEach(link => {
            link.classList.remove('active');
            if (link.dataset.lang === lang) {
                link.classList.add('active');
            }
        });

        // Fire event
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: lang }));
    }
};

document.addEventListener('DOMContentLoaded', () => {
    // Intercept language toggle clicks
    document.querySelectorAll('.lang-link').forEach(link => {
        link.addEventListener('click', (e) => {
            e.preventDefault();
            const lang = e.currentTarget.dataset.lang;
            if (lang && lang !== currentLang) {
                // Instantly update DOM
                window.setLanguage(lang);
                
                // Sync with server session silently
                const url = e.currentTarget.getAttribute('href');
                if (url) {
                    fetch(url, { method: 'GET' }).catch(console.error);
                }
            }
        });
    });
});
